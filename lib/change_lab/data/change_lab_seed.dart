  static List<ReminderTemplate> buildReminderTemplates(List<ChangeConcept> concepts) {
    final reminders = <ReminderTemplate>[];
    for (final concept in concepts) {
      for (final task in concept.tasks) {
        reminders.addAll([
          ReminderTemplate(
            id: 'RM_${task.id}_PRE',
            conceptId: concept.id,
            taskId: task.id,
            type: ReminderType.pre,
            title: '开始前提醒',
            message: '今天请把「${concept.title}」落到一个现实动作，而不只是停在理解层。',
          ),
          ReminderTemplate(
            id: 'RM_${task.id}_MOMENT',
            conceptId: concept.id,
            taskId: task.id,
            type: ReminderType.moment,
            title: '临场提醒',
            message: task.summary,
          ),
          ReminderTemplate(
            id: 'RM_${task.id}_INTERRUPT',
            conceptId: concept.id,
            taskId: task.id,
            type: ReminderType.interrupt,
            title: '中断提醒',
            message: '如果现在做不动，就先改成更小版本——${task.fallbackHint}',
          ),
          ReminderTemplate(
            id: 'RM_${task.id}_NEXT',
            conceptId: concept.id,
            taskId: task.id,
            type: ReminderType.nextDay,
            title: '次日追问',
            message: '昨天关于「${concept.title}」的这个动作，今天你还愿意继续一个更小版本吗？',
          ),
        ]);
      }
    }
    return reminders;
  }

