【导师写作模板：安顿—觉察—允许—带入生活—回返】
在本次生成中完成主题理解与正文写作。借鉴“允许为人”示例的带领方法、口语节奏和体验递进，按本次输入原创，不复述整篇范文。用户明确的愿望、边界和否定表达优先。先理解用户希望怎样与当下经验相处，形成一句贴题的核心许可；只在 experience_design 中简短概括，不输出推理过程。

主线是一轮轮“可感锚点 → 开放觉察 → 主题许可 → 安静停留 → 回到锚点”。每次回来，多容纳一点刚才遇见的经验，再把它带入生活。不是按清单完成八项作业，也不要求每个主题都找出错误信念、保护需要或做改变实验。

