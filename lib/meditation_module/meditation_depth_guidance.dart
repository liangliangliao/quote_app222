【主题认知转为可进入的身心体验】
在本次生成中完成主题理解与正文写作。用户原话是整篇的主线，用户明确的愿望、边界和否定表达优先。先准确理解原话中的概念、处境或愿望，再围绕一个关键区分写作；不要把所有输入改成“允许情绪存在”，也不凭一句话诊断经历、性格或创伤。承接参考导师的温暖、回返与留白，同时让听者真正理解本次主题。

主线：主题是什么 → 为什么重要或让人卡住 → 可以怎样尝试 → 概念与画面的对应 → 亲自进入并行动 → 身体和情绪观察 → 回看认知 → 生活延续。认知、画面与身心体验互相衔接，不是三块拼贴内容。少说教不等于少解释；安顿呼吸是入口，不能取代主题。

【把“是什么、为什么、怎么做”写进播报正文】
是什么：用贴近用户原话的语言说明核心含义及一个容易混淆的边界。比如“允许自己为人”包含为真实感受与有限性留位置；允许感受，不等于同意每个念头或按每个冲动行动。若输入是一段处境，先回应它的实际困境，不强行给它下抽象定义。
为什么：解释与本次输入有关的机制或意义，连接处境、理解/期待、情绪和应对之间的关系。区分用户明确说出的事实与“有时、可能、如果贴近你”的假设。不编造隐藏原因、他人想法或神经科学结论。比如本来已经难过，又要求自己“不准难过”，有时会多一层自责或抵抗；不是宣称所有不适都由想法造成。
怎么做：由这个区分推出一个具体、可选择的尝试，并说明为什么这个动作对应主题。不是统一回答“呼吸、放松肩膀”。可保留原有感受，同时改变与它的关系或下一步选择。
这些理解必须自然出现在 segments.text 中，不能只藏在 understood_need、cognitive_shift 或设计附注里。较长练习可把理解分成几个相连的短段，分布在进入画面之前、体验之中和整合之时；不在开头讲完一整课，也不把深度压缩成一句安慰。一次讲清一个关键关系，随后交给体验。

【把概念变成画面，而不是加一段风景】
