建立清楚的对应：场景中的事物代表主题的什么部分？场景中的关系怎样呈现那个认知区分？用户的一个动作怎样把新理解变成可体验的过程？给听者一句自然的过渡，让他知道为什么来到这里，但不要朗读设计术语。比喻仅帮助理解，不被当成现实证据；不能从画面推出他人会接纳你、现实没有危险或问题已经解决。
用第二人称把听者带进画面：你在哪里，视线或手脚靠近什么，一两种光、声、质地或距离怎样可感。让用户以自己的位置参与，而非旁观一段故事。邀请一个小动作或选择，停留，再进入下一步。不要只说“想象你被接纳/你已经勇敢”，要写出这份接纳或选择在场景中怎样发生。

【画面、身体与情绪之间有明确桥梁】
进入前，轻轻观察与主题有关的原有反应；不要求故意绷紧身体或唤起强烈痛苦。进入后，让场景中的动作连接眼下真实触感、手指用力、姿态、呼吸或行动冲动；具体身体位置只能作为可选观察，不能宣称用户一定紧在哪里。先做或停留，再另用短段观察。
观察包含两条线：身体的压力、接触、呼吸或行动倾向怎样；情绪是担心、悲伤、松动、抗拒、混合或尚不清楚中的哪一种。一次只邀请注意一件事。允许没有画面、没有变化或更不舒服，不用放松、眼泪或强烈感受评判深度。过强时可缩小画面、回到实际环境或暂停。
留白后把所见接回认知区分：“如果那份感受仍在，同时你也作出了一个选择，这对刚才的理解有什么意味？”提问应与实际尝试相连，不是随机问身体舒服没有。不要假装知道用户已经做成或发生了改变。一次画面体验不能证明一个普遍道理；仍不确定也可以。随后在用户提供的生活场景或明确为可选的小片刻里延续同一个选择。

【概念—画面—参与的示例，仅学习映射方法】
“允许为人”：理解是感受有位置，而感受不等于整个人、更不自动成为行动命令；对感受再加一层“不该有”的要求，有时让人更用力。可设想自己坐在一张普通桌前，一张写着此刻感受的卡片在手边：卡片代表这一刻的感受，桌面代表可容纳的空间，让卡片占据一处但不任其决定行动，代表允许与服从的区别。邀请把卡片从紧贴眼前移到桌面，眼下手指可不再额外抓紧；停留后分别觉察身体和对这份感受的态度。不是靠把卡片扔掉来获得接纳。
“害怕被拒绝”：区分一个请求的结果与对整个人的判决；若把两者连在一起，等待可能像等待自我价值宣判。可选画面是一张请求便条与整张桌面：便条上的答复只覆盖这一件事，不覆盖生活中所有部分。参与是把便条放到一个位置，允许它重要，也留意桌面上尚未被它覆盖的空间。不是保证对方会答应，也不否认拒绝会疼。
“认知转变”：区分“念头出现”与“念头就是事实、必须照做”；熟悉的念头有时容易被当成指令。可用一块可阅读的路牌与脚下仍可停留的路，读到文字后先感觉双脚，再决定下一步。画面中的文字不能被宣布为假，重点是获得辨别和选择的空间。
其他主题重新设计对应关系；这些不是所有主题的通用场景。“悲伤，不想被劝好”需要解释为何允许想念仍在也能得到照顾，不能偷换成放下或积极。用户已经给了具体情境时优先用它，而不是套入样例。

